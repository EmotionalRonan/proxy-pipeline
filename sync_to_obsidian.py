#!/usr/bin/env python3
"""
Step 5: Publish verified proxy nodes.

Two modes:

1) Local mode (default, when NOT running in GitHub Actions):
   Copy verified nodes + TCP-reachable nodes into the local Obsidian vault,
   upload to the dufs file server, then git add/commit/push in the Obsidian repo.

2) CI mode (when GITHUB_ACTIONS env var is set, e.g. GitHub Actions):
   Copy the same files into the repo's `dist/` directory. The workflow then
   commits & pushes `dist/*.yaml` back to the GitHub repo with GITHUB_TOKEN.
   The Obsidian/dufs steps are skipped (they are LAN-only and not reachable
   from CI).

Copy targets:
  - mihomo_verified_nodes.yaml → verified_proxies.yaml (mihomo-tested working nodes)
  - reachable_nodes.yaml       → tcp_reachable.yaml      (TCP-screened reachable nodes)
"""

import os
import sys
import shutil
import subprocess
import datetime
import yaml

# ===== CONFIG =====
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

FILES_TO_SYNC = [
    {
        "source": os.path.join(SCRIPT_DIR, "mihomo_results_v2", "mihomo_verified_nodes.yaml"),
        "target_name": "verified_proxies.yaml",
        "label": "mihomo-verified",
    },
    {
        "source": os.path.join(SCRIPT_DIR, "screening_results", "reachable_nodes.yaml"),
        "target_name": "tcp_reachable.yaml",
        "label": "TCP-reachable",
    },
]

# Local (Obsidian) mode paths — overridable via env vars
TARGET_DIR = os.environ.get("OBSIDIAN_TARGET_DIR") or os.path.expanduser("~/Project/ObProject/obs/proyl")
REPO_DIR = os.environ.get("OBSIDIAN_REPO_DIR") or os.path.expanduser("~/Project/ObProject/obs")
DUFS_URL = os.environ.get("DUFS_URL") or "http://192.168.1.100:6990"

# CI mode: copy results into repo dist/ (default: <repo-root>/dist)
IS_CI = bool(os.environ.get("GITHUB_ACTIONS"))
CI_OUTPUT_DIR = os.environ.get("CI_OUTPUT_DIR") or os.path.join(SCRIPT_DIR, "dist")


def run_cmd(cmd, cwd, timeout=30):
    """Run a shell command and return stdout/stderr."""
    result = subprocess.run(
        cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout
    )
    return result.returncode, result.stdout.strip(), result.stderr.strip()


def count_nodes(filepath):
    """Count proxy nodes in a YAML file."""
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            data = yaml.safe_load(f)
            if data and "proxies" in data:
                return len(data["proxies"])
    except Exception:
        pass
    return 0


def sync_ci_mode():
    """CI mode: copy verified nodes into the repo dist/ directory."""
    print("=" * 60)
    print("  SYNC (CI MODE) → repo dist/")
    print("=" * 60)

    os.makedirs(CI_OUTPUT_DIR, exist_ok=True)
    synced = []

    for entry in FILES_TO_SYNC:
        source = entry["source"]
        target_name = entry["target_name"]
        label = entry["label"]

        if not os.path.exists(source):
            print(f"\n  [{label}] Source not found: {source} — skipping")
            continue

        target = os.path.join(CI_OUTPUT_DIR, target_name)
        shutil.copy2(source, target)
        count = count_nodes(source)
        synced.append((label, target_name, count))
        print(f"  [{label}] {source}")
        print(f"           → {target}")
        print(f"           {count} nodes")

    # Write a small index so the dist/ folder is self-documenting
    with open(os.path.join(CI_OUTPUT_DIR, "README.md"), "w") as f:
        f.write(f"# Proxy node snapshot — {datetime.date.today().isoformat()}\n\n")
        f.write("Auto-generated by the daily proxy pipeline (GitHub Actions).\n\n")
        if synced:
            for label, name, count in synced:
                f.write(f"- `{name}`: {count} {label} nodes\n")
        else:
            f.write("- (no files generated this run)\n")
        f.write("\n## Subscribe (Clash / Mihomo)\n\n")
        f.write("Use the raw URL of `verified_proxies.yaml` as your subscription link.\n")

    print(f"\n  CI sync complete → {CI_OUTPUT_DIR}")
    print(f"  (the workflow will git add dist/ && commit && push)\n")
    return 0


def main():
    if IS_CI:
        return sync_ci_mode()

    print("=" * 60)
    print("  SYNC TO OBSIDIAN + GIT PUSH")
    print("=" * 60)

    today = datetime.date.today().isoformat()
    os.makedirs(TARGET_DIR, exist_ok=True)

    synced = []
    node_counts = {}

    for entry in FILES_TO_SYNC:
        source = entry["source"]
        target_name = entry["target_name"]
        target = os.path.join(TARGET_DIR, target_name)
        label = entry["label"]

        if not os.path.exists(source):
            print(f"\n  [{label}] Source not found: {source} — skipping")
            continue

        shutil.copy2(source, target)
        count = count_nodes(source)
        node_counts[label] = count
        synced.append((label, target_name, count))
        print(f"\n  [{label}] {source}")
        print(f"           → {target}")
        print(f"           {count} nodes")

    if not synced:
        print("\n  No files to sync. Skipping.")
        return 1

    # ---- Dufs upload ----
    print(f"\n  Dufs upload to {DUFS_URL} ...")
    dufs_ok = True
    for entry in FILES_TO_SYNC:
        source = entry["source"]
        target_name = entry["target_name"]
        label = entry["label"]
        if not os.path.exists(source):
            continue
        url = f"{DUFS_URL}/{target_name}"
        ret, out, err = run_cmd(
            ["curl", "-s", "-X", "PUT", url,
             "-H", "Content-Type: application/octet-stream",
             "--data-binary", f"@{source}"],
            cwd=SCRIPT_DIR, timeout=30
        )
        if ret != 0:
            print(f"  [{label}] Upload failed: {err}")
            dufs_ok = False
        else:
            print(f"  [{label}] {url}  OK")
    if dufs_ok:
        print(f"  Dufs upload complete")
    else:
        print(f"  Dufs upload had errors (continuing)")

    # ---- Build commit message ----
    parts = [f"proxy: daily update ({today})"]
    for label, _, count in synced:
        parts.append(f"{label}: {count} nodes")
    commit_msg = "\n".join(parts)

    # ---- Git operations ----
    print(f"\n  Git add...")
    target_files = [os.path.join("proyl", tname) for _, tname, _ in synced]
    ret, out, err = run_cmd(["git", "add"] + target_files, cwd=REPO_DIR)
    if ret != 0:
        print(f"  git add failed: {err}")
        return 1
    print(f"  OK")

    print(f"\n  Git commit...")
    ret, out, err = run_cmd(["git", "commit", "-m", commit_msg], cwd=REPO_DIR)
    if ret == 0:
        print(f"  OK: {out}")
    elif "nothing to commit" in (out + err):
        print(f"  Nothing to commit (no changes). Skipping push.")
        return 0
    else:
        print(f"  Commit failed: {err}")
        return 1

    print(f"\n  Git push...")
    ret, out, err = run_cmd(["git", "push"], cwd=REPO_DIR, timeout=60)
    if ret != 0:
        print(f"  Push failed: {err}")
        return 1
    print(f"  OK: {out}")

    print(f"\n{'=' * 60}")
    print(f"  SYNC COMPLETE")
    for label, tname, count in synced:
        print(f"  {tname}: {count} {label} nodes")
    print(f"{'=' * 60}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
